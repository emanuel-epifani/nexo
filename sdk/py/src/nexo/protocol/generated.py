from enum import IntEnum

PROTOCOL_VERSION = 0x06

HEADER_SIZE = 11
HEADER_OFFSET_VERSION = 0
HEADER_OFFSET_TYPE = 1
HEADER_OFFSET_META = 2
HEADER_OFFSET_ID = 3
HEADER_OFFSET_PAYLOAD_LEN = 7


class FrameType(IntEnum):
    REQUEST = 0x01
    RESPONSE = 0x02
    PUSH_PUBSUB = 0x03
    REQUEST_NO_RESPONSE = 0x04


class ResponseStatus(IntEnum):
    OK = 0x00
    ERR = 0x01
    NULL = 0x02
    DATA = 0x03


class DataType(IntEnum):
    RAW = 0x00
    STRING = 0x01
    JSON = 0x02
    INT = 0x03


class StoreOpcode:
    MAP_SET = 0x02
    MAP_GET = 0x03
    MAP_DEL = 0x04
    MAP_INCR = 0x05
    MAP_CLEAR_ALL = 0x06
    MAP_CLEAR_PREFIX = 0x07

class QueueOpcode:
    Q_CREATE = 0x10
    Q_PUSH = 0x11
    Q_CONSUME = 0x12
    Q_ACK = 0x13
    Q_EXISTS = 0x14
    Q_DELETE = 0x15
    Q_PEEK_DLQ = 0x16
    Q_MOVE_TO_QUEUE = 0x17
    Q_DELETE_DLQ = 0x18
    Q_PURGE_DLQ = 0x19
    Q_NACK = 0x1A

class PubSubOpcode:
    PUB = 0x21
    SUB = 0x22
    UNSUB = 0x23

class StreamOpcode:
    S_CREATE = 0x30
    S_PUB = 0x31
    S_FETCH = 0x32
    S_JOIN = 0x33
    S_ACK = 0x34
    S_EXISTS = 0x35
    S_DELETE = 0x36
    S_SEEK = 0x38
    S_LEAVE = 0x39
    S_PEEK_DLT = 0x3A
    S_MOVE_TO_STREAM = 0x3B
    S_DELETE_DLT = 0x3C
    S_PURGE_DLT = 0x3D

QUEUE_MAX_PUSH_ITEMS = 10_000
STREAM_MAX_PUBLISH_BATCH = 65_536
STREAM_MAX_FETCH_BATCH_SIZE = 65_536
STREAM_MAX_KEY_BYTES = 65_535

FLAG_STORE_MAP_SET_HAS_TTL = 0x01
FLAG_QUEUE_Q_CREATE_HAS_VISIBILITY_TIMEOUT = 0x01
FLAG_QUEUE_Q_CREATE_HAS_MAX_DELIVERIES = 0x02
FLAG_QUEUE_Q_PUSH_HAS_PRIORITY = 0x01
FLAG_PUBSUB_PUB_RETAIN = 0x01
FLAG_PUBSUB_PUB_HAS_TTL = 0x02
FLAG_PUBSUB_PUB_CLEAR = 0x04
FLAG_STREAM_S_CREATE_HAS_MAX_AGE = 0x01
FLAG_STREAM_S_CREATE_HAS_MAX_BYTES = 0x02
